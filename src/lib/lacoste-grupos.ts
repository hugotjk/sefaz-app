const semAcento = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
const chave = (s: string) => semAcento(s).toUpperCase().replace(/\s+/g, " ").trim();

const MAPA = new Map<string, string>(PARES.map(([t, g]) => [chave(t), g.toUpperCase()]));

/**
 * Acha o tipo Lacoste no começo da descrição (tira palavras do fim até casar,
 * já que o fim é a referência). Devolve o tipo e o grupo (MAIÚSCULO), ou null.
 */
export function tipoEGrupoLacoste(descricao: string): { tipo: string; grupo: string } | null {
  const palavras = descricao.replace(/\s+/g, " ").trim().split(" ");
  for (let n = palavras.length; n >= 1; n--) {
    const tipo = palavras.slice(0, n).join(" ");
    const g = MAPA.get(chave(tipo));
    if (g) return { tipo: tipo.toUpperCase(), grupo: g };
  }
  return null;
}
